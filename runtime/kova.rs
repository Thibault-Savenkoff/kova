// ---- Lists ----
// A List is a fixed block (so its address never changes) holding its elements, `width` slots
// each, one after the other. 0 = no List (moved): freeing it does nothing.
// A Map or a Set also has an `index` (a table of positions, made by `find_in_index` in
// src/kir.rs): freed with it; `unindex` takes a removed element out of it.

struct List {
    length: usize,
    width: usize,
    slots: Vec<i64>,
    index: i64,
}

fn new_list(l: List) -> i64 {
    made();
    Box::into_raw(Box::new(l)) as i64
}

#[allow(clippy::mut_from_ref)]
fn list<'a>(l: i64) -> &'a mut List {
    unsafe { &mut *(l as *mut List) }
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_new(width: i64) -> i64 {
    new_list(List { length: 0, width: width as usize, slots: Vec::new(), index: 0 })
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_length(l: i64) -> i64 {
    if l == 0 { 0 } else { list(l).length as i64 }
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_check(l: i64, i: i64, line: i64, col: i64) {
    if i < 0 || i >= list(l).length as i64 {
        kova_fault(FAULT_INDEX, line, col);
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_load(l: i64, i: i64, k: i64) -> i64 {
    let l = list(l);
    l.slots[i as usize * l.width + k as usize]
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_store(l: i64, i: i64, k: i64, v: i64) {
    let l = list(l);
    l.slots[i as usize * l.width + k as usize] = v;
}

/// One more element at the end (slots set to 0); returns its index.
#[unsafe(no_mangle)]
pub extern "C" fn kova_list_grow(l: i64) -> i64 {
    let l = list(l);
    l.slots.resize(l.slots.len() + l.width, 0);
    l.length += 1;
    l.length as i64 - 1
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_remove(l: i64, i: i64) {
    let l = list(l);
    if l.index != 0 {
        shared::unindex(&mut list(l.index).slots, i);
    }
    let w = l.width;
    l.slots.drain(i as usize * w..(i as usize + 1) * w);
    l.length -= 1;
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_free(l: i64) {
    if l != 0 {
        let l = unsafe { Box::from_raw(l as *mut List) };
        kova_list_free(l.index);
        LIVE.fetch_sub(1, Relaxed);
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_index(l: i64) -> i64 {
    if l == 0 { 0 } else { list(l).index }
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_list_set_index(l: i64, index: i64) {
    list(l).index = index;
}

// ---- Files and input: a String or 0 (or a new value) when it works, else minus the failure,
// numbered like `IoError` (src/types.rs `io_error`): 1 NotFound, 2 Denied, 3 IsDirectory,
// 4 NotText, 5 Other. Like src/interp.rs; `sys` gives each failure its number. ----

/// The path, or None if it holds a 0 byte (no file has such a name).
fn path(p: i64) -> Option<&'static str> {
    Some(text_of(p)).filter(|p| !p.contains('\0'))
}

fn is_dir(path: &str) -> bool {
    sys::kind(path) == Ok(true)
}

fn result(r: Result<(), i64>) -> i64 {
    r.err().map_or(0, |f| -f)
}

/// `read_file(path)`: the file's text as a String.
#[unsafe(no_mangle)]
pub extern "C" fn kova_read_file(p: i64) -> i64 {
    match path(p) {
        None => -5,
        // Windows answers "denied" for a directory: asked first.
        Some(p) if is_dir(p) => -3,
        Some(p) => match sys::read_file(p).map(String::from_utf8) {
            Ok(Ok(text)) => new_text(text.as_bytes()),
            Ok(Err(_)) => -4,
            Err(f) => -f,
        },
    }
}

fn put_file(p: i64, t: i64, append: bool) -> i64 {
    match path(p) {
        None => -5,
        Some(p) if is_dir(p) => -3,
        Some(p) => result(sys::write_file(p, bytes(t), append)),
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_write_file(p: i64, t: i64) -> i64 {
    put_file(p, t, false)
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_append_file(p: i64, t: i64) -> i64 {
    put_file(p, t, true)
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_exists(p: i64) -> i64 {
    path(p).is_some_and(|p| sys::kind(p).is_ok()) as i64
}

/// The names in a directory (without `.` and `..`), in the order of their bytes: the system
/// gives them in no particular order.
#[unsafe(no_mangle)]
pub extern "C" fn kova_list_dir(p: i64) -> i64 {
    let Some(p) = path(p) else { return -5 };
    match sys::list_dir(p) {
        Ok(mut names) => {
            names.sort();
            texts(names.iter().map(String::as_str))
        }
        Err(f) => -f,
    }
}

/// Like `mkdir -p`: the missing parents too; a directory already there is fine.
#[unsafe(no_mangle)]
pub extern "C" fn kova_make_dir(p: i64) -> i64 {
    let Some(p) = path(p) else { return -5 };
    if p.is_empty() {
        return -1;
    }
    // Each parent, then the whole path (`C:` on Windows cannot be made but is there).
    let ends = p.char_indices().skip(1).filter(|&(_, c)| c == '/' || c == sys::SLASH).map(|(i, _)| i);
    for end in ends.chain([p.len()]) {
        let part = &p[..end];
        let made = sys::make_dir(part);
        if !is_dir(part) {
            // Made or already there, but not a directory: a file has this name.
            return -match made {
                Ok(()) | Err(0) => 5,
                Err(f) => f,
            };
        }
    }
    0
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_remove_file(p: i64) -> i64 {
    match path(p) {
        None => -5,
        Some(p) if is_dir(p) => -3,
        Some(p) => result(sys::remove_file(p)),
    }
}

/// What was read from the input and not given to `read_line` yet, from `.1` on.
static INPUT: Global<(Vec<u8>, usize)> = Global::new((Vec::new(), 0));

/// `read_line`: the next line of the input without its end (`\n` or `\r\n`),
/// 0 at the end of the input, -1 if the line is not UTF-8 (src/kir.rs stops the program).
#[unsafe(no_mangle)]
pub extern "C" fn kova_read_line() -> i64 {
    flush();
    let (input, at) = INPUT.get();
    let mut line = Vec::new();
    let mut read = false;
    loop {
        if *at == input.len() {
            input.resize(1 << 16, 0);
            let n = sys::read(0, input);
            input.truncate(n);
            *at = 0;
            if n == 0 {
                break;
            }
        }
        read = true;
        let rest = &input[*at..];
        match rest.iter().position(|&b| b == b'\n') {
            Some(k) => {
                line.extend_from_slice(&rest[..k]);
                *at += k + 1;
                break;
            }
            None => {
                line.extend_from_slice(rest);
                *at = input.len();
            }
        }
    }
    if !read {
        return 0;
    }
    if line.last() == Some(&b'\r') {
        line.pop();
    }
    if core::str::from_utf8(&line).is_ok() { new_text(&line) } else { -1 }
}

/// `args`: the words after the program's name.
static ARGS: Global<Vec<String>> = Global::new(Vec::new());

#[unsafe(no_mangle)]
pub extern "C" fn kova_args() -> i64 {
    texts(ARGS.get().iter().skip(1).map(String::as_str))
}

// ---- Time and chance (src/interp.rs does the same) ----

/// `now`: the seconds since 1970 (UTC), as a Float's bits.
#[unsafe(no_mangle)]
pub extern "C" fn kova_now() -> i64 {
    let t = sys::now();
    ((t / 1_000_000_000) as f64 + (t % 1_000_000_000) as f64 / 1e9).to_bits() as i64
}

/// `sleep(seconds)`, a Float's bits: what `print` left is shown first; 0 or less waits nothing.
#[unsafe(no_mangle)]
pub extern "C" fn kova_sleep(bits: i64) -> i64 {
    let s = f64::from_bits(bits as u64);
    flush();
    if s > 0.0 && s < 1e9 {
        sys::sleep(s);
    }
    0
}

/// `random(from..to)`: the state is started at the first call.
#[unsafe(no_mangle)]
pub extern "C" fn kova_random(from: i64, to: i64) -> i64 {
    static CHANCE: Global<Option<u64>> = Global::new(None);
    let state = CHANCE.get().get_or_insert_with(|| {
        shared::seed(sys::var("KOVA_SEED").as_deref()).unwrap_or_else(|| sys::now() ^ sys::pid() << 32)
    });
    shared::random(state, from, to)
}

