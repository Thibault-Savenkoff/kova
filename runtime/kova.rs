// Kova runtime: the small piece of Rust glued to every executable (`kova build`), without
// Rust's `std` (only `core` and `alloc`): what it needs from the system is in `sys`, one file per
// system. `build.rs` compiles it when `kova` itself is built, and `kova` carries it inside.
// Messages must be identical to the interpreter's (src/kir.rs, `fault_text`); the code that
// computes or writes values is shared with it (src/shared.rs, src/bigint.rs).
// Its texts come from `locales/*.kova`, written as data by `kova build` (src/codegen.rs, `runtime_texts`).

