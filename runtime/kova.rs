/// The local time at `utc`, by the rules of that day.
fn local_at(utc: i64) -> i64 {
    #[cfg(not(windows))]
    return utc + shared::local_offset(utc, sys::var("TZ").as_deref(), &|p| sys::read_file(p).ok());
    #[cfg(windows)]
    sys::local_at(utc)
}

