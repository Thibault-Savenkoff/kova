/// The names in a directory (without `.` and `..`), in the order of their bytes: the system
/// gives them in no particular order.
#[unsafe(no_mangle)]
pub extern "C" fn kova_list_dir(p: i64) -> i64 {
    let Some(p) = path(p) else { return -5 };
    match sys::list_dir(p) {
        Ok(mut names) => {
            names.sort();
            texts(names.iter().map(String::as_str))
        }
        Err(f) => -f,
    }
}

/// Like `mkdir -p`: the missing parents too; a directory already there is fine.
#[unsafe(no_mangle)]
pub extern "C" fn kova_make_dir(p: i64) -> i64 {
    let Some(p) = path(p) else { return -5 };
    if p.is_empty() {
        return -1;
    }
    // Each parent, then the whole path (`C:` on Windows cannot be made but is there).
    let ends = p.char_indices().skip(1).filter(|&(_, c)| c == '/' || c == sys::SLASH).map(|(i, _)| i);
    for end in ends.chain([p.len()]) {
        let part = &p[..end];
        let made = sys::make_dir(part);
        if !is_dir(part) {
            // Made or already there, but not a directory: a file has this name.
            return -match made {
                Ok(()) | Err(0) => 5,
                Err(f) => f,
            };
        }
    }
    0
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_remove_file(p: i64) -> i64 {
    match path(p) {
        None => -5,
        Some(p) if is_dir(p) => -3,
        Some(p) => result(sys::remove_file(p)),
    }
}

/// What `sys::info` knows of a file; `modified` in seconds since 1970 (UTC).
pub struct Info {
    pub folder: bool,
    pub link: bool,
    pub size: i64,
    pub modified: i64,
}

/// Read whole then written, so that copying a file onto itself loses nothing (as interp.rs).
/// ponytail: the whole file in memory, and its permissions are not copied (a copied program
/// cannot be run); a piece at a time, with the permissions, when someone needs it.
fn copy_file(a: &str, b: &str) -> i64 {
    if is_dir(a) {
        return -3;
    }
    if is_dir(b) {
        return -(3 + 16);
    }
    match sys::read_file(a) {
        Ok(bytes) => sys::write_file(b, &bytes, false).err().map_or(0, |f| -(f + 16)),
        Err(f) => -f,
    }
}

/// `files.copy(a) to(b)`: a failure past 16 is `b`'s (src/kir.rs `io_result`).
#[unsafe(no_mangle)]
pub extern "C" fn kova_copy_file(a: i64, b: i64) -> i64 {
    match (path(a), path(b)) {
        (Some(a), Some(b)) => copy_file(a, b),
        (None, _) => -5,
        _ => -(5 + 16),
    }
}

/// `files.move(a) to(b)`: renamed, or copied then removed when `b` is on another disk.
#[unsafe(no_mangle)]
pub extern "C" fn kova_move_file(a: i64, b: i64) -> i64 {
    let Some(a) = path(a) else { return -5 };
    let Some(b) = path(b) else { return -(5 + 16) };
    if let Err(f) = sys::kind(a) {
        return -f;
    }
    if is_dir(b) {
        return -(3 + 16);
    }
    match sys::rename(a, b) {
        Ok(()) => 0,
        Err(0) => match copy_file(a, b) {
            0 => result(sys::remove_file(a)),
            f => f,
        },
        Err(f) => -(f + 16),
    }
}

/// `files.size(path)`: a folder has none.
#[unsafe(no_mangle)]
