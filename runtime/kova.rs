// ---- The web server (src/http.rs reads the questions and writes the answers) ----

/// A socket, as each system numbers it.
#[cfg(target_os = "macos")]
type Socket = i32;
#[cfg(not(target_os = "macos"))]
type Socket = usize;

#[unsafe(no_mangle)]
pub extern "C" fn kova_listen(port: i64, everyone: i64, folder: i64, log: i64) -> i64 {
    use http::Serve;
    let everyone = everyone != 0;
    let Some((port, l)) = u16::try_from(port).ok().filter(|&p| p > 0).and_then(|p| sys::Net.listen(p, everyone).map(|l| (p, l))) else {
        return -1;
    };
    // `{port}`, `{folder}`: the holes `locale::RUNTIME_HOLES` leaves in these texts.
    let fill = |i: usize| String::from_utf8_lossy(text(i)).replace("{port}", &alloc::format!("{port}"));
    let title = if folder == 0 { fill(SERVING) } else { fill(SERVING_FILES).replace("{folder}", &http::shown_folder(text_of(folder))) };
    let words = |i: usize| String::from_utf8_lossy(text(i)).into_owned();
    let (computer, network, stop) = (words(if everyone { THIS_COMPUTER } else { THIS_COMPUTER_ONLY }), words(THIS_NETWORK), words(STOP_WITH_CTRL_C));
    let said = http::Said { title: &title, this_computer: &computer, this_network: &network, stop: &stop };
    let addresses = if everyone { sys::Net.addresses() } else { Vec::new() };
    if log < 2 {
        error(http::banner(port, everyone, &addresses, &said).as_bytes());
    }
    alloc::boxed::Box::into_raw(alloc::boxed::Box::new(http::Server::<sys::Net>::new(l, log == 0))) as i64
}

/// A question being answered: its connection, then who asked, its method and its URL if it is
/// written when answered.
type Asked = (Socket, Option<([u8; 4], String, String)>);

/// Like src/interp.rs.
#[unsafe(no_mangle)]
pub extern "C" fn kova_accept(server: i64) -> i64 {
    // With `workers(…)`, the thread that has it reads every connection until one question is
    // whole, then lets the next one read (the others are answering, or wait here).
    static READING: Locked<()> = Locked::new(());
    let (link, q, from, logs) = READING.with(|_| {
        let server = unsafe { &mut *(server as *mut http::Server<sys::Net>) };
        let (link, q, from) = http::next_question(&mut sys::Net, server);
        (link, q, from, server.logs)
    });
    let asked: Asked = (link, logs.then(|| (from, q.method.clone(), q.url.clone())));
    let link = alloc::boxed::Box::into_raw(alloc::boxed::Box::new(asked));
    let length = q.headers.len();
    let slots = q.headers.iter().flat_map(|(n, v)| [new_text(n.as_bytes()), new_text(v.as_bytes())]).collect();
    let headers = new_list(List { length, width: 2, slots, index: 0, small: None });
    let slots = alloc::vec![new_text(q.method.as_bytes()), new_text(q.url.as_bytes()), headers, new_text(q.body.as_bytes()), 0, 0, byte_list(q.data), link as i64];
    new_list(List { length: 1, width: 8, slots, index: 0, small: None })
}

/// `serve(…) workers(n)` (src/kir.rs `StrOp::Workers`): `worker(env)` on `n` threads, this one
/// included. A worker never returns: an `exit` or an error on any thread stops the program.
#[unsafe(no_mangle)]
pub extern "C" fn kova_workers(n: i64, worker: i64, env: i64) -> i64 {
    let worker: extern "C" fn(i64) = unsafe { core::mem::transmute(worker as usize) };
    // A thread the system cannot start (no memory left): the others answer. They never end.
    for _ in 1..n {
        THREADS.fetch_add(1, SeqCst);
        if sys::spawn(worker, env).is_none() {
            THREADS.fetch_sub(1, SeqCst);
            break;
        }
    }
    worker(env);
    0
}

/// `l.map workers(n) { … }`, `l.each workers(n) { … }` (src/kir.rs `StrOp::Parallel`):
/// `worker(env, next)` on up to `n` threads, this one included, then waits for them. Each takes
/// the next element to do from `next` (`kova_next`) until there is none left: a slow element
/// keeps one thread only.
// ponytail: threads are made at each call; a pool kept between calls if it runs in a hot loop.
#[unsafe(no_mangle)]
pub extern "C" fn kova_parallel(n: i64, length: i64, worker: i64, env: i64) -> i64 {
    let worker: extern "C" fn(i64, i64) = unsafe { core::mem::transmute(worker as usize) };
    let next = AtomicI64::new(0);
    let job = (worker, env, &next as *const AtomicI64 as i64);
    extern "C" fn member(job: i64) {
        let &(worker, env, next) = unsafe { &*(job as *const (extern "C" fn(i64, i64), i64, i64)) };
        worker(env, next);
        thread_ended();
    }
    let start = |_| {
        THREADS.fetch_add(1, SeqCst);
        let thread = sys::spawn(member, &job as *const _ as i64);
        if thread.is_none() {
            THREADS.fetch_sub(1, SeqCst);
        }
        thread
    };
    let threads: Vec<sys::Thread> = (1..n.min(length)).map_while(start).collect();
    worker(env, job.2);
    threads.into_iter().for_each(sys::join);
    0
}

