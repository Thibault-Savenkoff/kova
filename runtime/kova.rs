/// `fault` = the number of its text.
#[unsafe(no_mangle)]
pub extern "C" fn kova_fault(fault: i64, line: i64, col: i64) {
    let mut m = Vec::new();
    m.extend_from_slice(text(ERROR_PREFIX));
    m.extend_from_slice(text(fault as usize));
    m.extend_from_slice(b"\n  --> ");
    kova_show_site(&mut m, line);
    m.push(b':');
    put_int(&mut m, col);
    m.push(b'\n');
    error(&m);
    exit(101)
}

