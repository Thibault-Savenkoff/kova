// ---- `extern` (PLAN Part 4 "`extern`, step 1") ----

/// A String given to C: a copy ended by a 0 byte (none if `present` is 0), or -1 if it holds one.
#[unsafe(no_mangle)]
pub extern "C" fn kova_c_text(s: i64, present: i64) -> i64 {
    if present == 0 {
        return 0;
    }
    // Not `CString`: freeing one calls `strlen`, which a Windows program does not have.
    let b = bytes(s);
    if b.contains(&0) {
        return -1;
    }
    Box::into_raw([b, &[0]].concat().into_boxed_slice()) as *mut u8 as i64
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_c_free(c: i64) -> i64 {
    if c > 0 {
        let n = c_bytes(c as *const u8).len() + 1;
        drop(unsafe { Box::from_raw(core::ptr::slice_from_raw_parts_mut(c as *mut u8, n)) });
    }
    0
}

/// The bytes up to the 0 at `p`; read one by one (`read_volatile`: a loop LLVM would turn into a
/// call of `strlen`, which a Windows program does not have).
fn c_bytes<'a>(p: *const u8) -> &'a [u8] {
    let mut n = 0;
    while unsafe { p.add(n).read_volatile() } != 0 {
        n += 1;
    }
    unsafe { core::slice::from_raw_parts(p, n) }
}

/// The String a C function gave: a copy (C keeps its own), 0 for NULL.
#[unsafe(no_mangle)]
pub extern "C" fn kova_from_c_text(p: i64) -> i64 {
    if p == 0 {
        return 0;
    }
    new_text(String::from_utf8_lossy(c_bytes(p as *const u8)).as_bytes())
}

/// A String as a UTF-16 text ended by a 0, for Windows' `…W` functions (PLAN Part 4 "`extern`,
/// step 4"); freed by `kova_c_wide_free`. 0 for `none`, -1 if it holds a 0.
#[unsafe(no_mangle)]
pub extern "C" fn kova_c_wide_text(s: i64, present: i64) -> i64 {
    if present == 0 {
        return 0;
    }
    let b = bytes(s);
    if b.contains(&0) {
        return -1;
    }
    let units: Vec<u16> = String::from_utf8_lossy(b).encode_utf16().chain(core::iter::once(0)).collect();
    Box::into_raw(units.into_boxed_slice()) as *mut u16 as i64
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_c_wide_free(c: i64) -> i64 {
    if c > 0 {
        let n = wide_units(c as *const u16).len() + 1;
        drop(unsafe { Box::from_raw(core::ptr::slice_from_raw_parts_mut(c as *mut u16, n)) });
    }
    0
}

/// The UTF-16 units up to the 0 at `p` (`read_volatile`, as `c_bytes`).
fn wide_units<'a>(p: *const u16) -> &'a [u16] {
    let mut n = 0;
    while unsafe { p.add(n).read_volatile() } != 0 {
        n += 1;
    }
    unsafe { core::slice::from_raw_parts(p, n) }
}

/// The String a C function gave as UTF-16: a copy, 0 for NULL.
#[unsafe(no_mangle)]
pub extern "C" fn kova_from_c_wide_text(p: i64) -> i64 {
    if p == 0 {
        return 0;
    }
    new_text(String::from_utf16_lossy(wide_units(p as *const u16)).as_bytes())
}

/// A leaf of a C struct at `address` (PLAN Part 4 "`extern`, step 4"): a 4-byte `int` (`kind`
/// 1, made 64 bits) or 8 bytes; 0 at NULL.
#[unsafe(no_mangle)]
pub extern "C" fn kova_pointer_read(address: i64, size: i64) -> i64 {
    byte_list(unsafe { core::slice::from_raw_parts(address as *const u8, size.max(0) as usize) }.to_vec())
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_pointer_write(address: i64, l: i64) -> i64 {
    let bytes = bytes_of(l);
    unsafe { core::ptr::copy_nonoverlapping(bytes.as_ptr(), address as *mut u8, bytes.len()) };
    0
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_c_read(address: i64, offset: i64, kind: i64) -> i64 {
    if address == 0 {
        return 0;
    }
    let p = (address + offset) as *const u8;
    unsafe { if kind == 1 { (p as *const i32).read_unaligned() as i64 } else { (p as *const i64).read_unaligned() } }
}

/// `ui.show(title, view, width, height)` (src/ui.rs): the window shows the view, first at that
/// size (0: fit the content); the number of the button
/// clicked, or -1 once the window is closed. With `KOVA_UI_SCRIPT`, no window (the tests): the
/// view is printed, and the button to click read from the input (end of input = closed).
#[unsafe(no_mangle)]
pub extern "C" fn kova_ui_show(title: i64, view: i64, width: i64, height: i64) -> i64 {
    let (title, view) = (text_of(title), text_of(view));
    let acts = UI_ACTS.with(core::mem::take);
    if sys::var("KOVA_UI_SCRIPT").is_some() {
        OUT.with(|out| out.extend_from_slice(alloc::format!("[{title}] {}\n", shared::ui_describe(view)).as_bytes()));
        for act in &acts {
            OUT.with(|out| out.extend_from_slice(alloc::format!("({})\n", shared::ui_act_name(*act)).as_bytes()));
        }
        flush();
        if acts.contains(&1) {
            return -1;
        }
        let line = INPUT.with(|(input, at)| read_line(input, at));
        if line <= 0 {
            return -1;
        }
        let (clicked, typed) = shared::ui_answer(text_of(line));
        kova_str_free(line);
        if let Some(t) = typed {
            UI_TYPED.with(|now| *now = t);
        }
        return clicked;
    }
    flush();
    let mut typed = String::new();
    let clicked = sys::ui_show(title, &shared::ui_tree(view), width as i32, height as i32, &acts, &mut typed);
    if clicked <= -2 {
        UI_TYPED.with(|now| *now = typed);
    }
    clicked
}

/// What the field that changed last holds (`ui.typed`).
static UI_TYPED: Locked<String> = Locked::new(String::new());

#[unsafe(no_mangle)]
pub extern "C" fn kova_ui_typed() -> i64 {
    UI_TYPED.with(|now| new_text(now.as_bytes()))
}

/// The real size of each canvas of the view, as its window last said, and the next one made.
static UI_ROOMS: Locked<(Vec<(i32, i32)>, usize)> = Locked::new((Vec::new(), 0));

/// `ui.room`: 0 the width, 1 the height of the canvas being made (a guess before its window
/// has said), 2 a new view starts.
#[unsafe(no_mangle)]
pub extern "C" fn kova_ui_room(which: i64) -> i64 {
    if which > 2 {
        let areas = if sys::var("KOVA_UI_SCRIPT").is_some() { None } else { sys::ui_areas() };
        return areas.unwrap_or(shared::UI_AREAS_GUESS)[which as usize - 3] as i64;
    }
    UI_ROOMS.with(|(rooms, next)| {
        if which == 2 {
            *next = 0;
            return 0;
        }
        let (width, height) = rooms.get(*next).copied().unwrap_or((320, 200));
        (if which == 0 { width } else { height }) as i64
    })
}

/// A window says how big canvas `k` really is; true if that is news.
pub fn ui_room(k: usize, width: i32, height: i32) -> bool {
    UI_ROOMS.with(|(rooms, _)| {
        if rooms.len() <= k {
            rooms.resize(k + 1, (0, 0));
        }
        core::mem::replace(&mut rooms[k], (width, height)) != (width, height)
    })
}

