/// `exit(code)`: what is still alive is not freed, and not counted as a leak (src/interp.rs too).
#[unsafe(no_mangle)]
pub extern "C" fn kova_exit(code: i64) {
    // `KOVA_LEAKS=live`: like `alive` in src/interp.rs.
    if sys::var("KOVA_LEAKS").is_some_and(|m| m == "live") {
        let mut m = b"alive: ".to_vec();
        put_int(&mut m, LIVE.load(Relaxed));
        m.push(b'\n');
        error(&m);
    }
    exit(code as i32)
}

/// How many Strings and Lists were made, and how many are not freed yet.
static ALLOCATED: AtomicI64 = AtomicI64::new(0);
static LIVE: AtomicI64 = AtomicI64::new(0);

fn made() {
    ALLOCATED.fetch_add(1, Relaxed);
    LIVE.fetch_add(1, Relaxed);
}

/// With KOVA_LEAKS set (the test runner sets it): a String never freed is an error (code 102);
/// `KOVA_LEAKS=count` also prints how many were made. Same as `leaks` in src/interp.rs.
fn leaks() -> i32 {
    let Some(mode) = sys::var("KOVA_LEAKS") else { return 0 };
    let mut m = Vec::new();
    if mode == "count" {
        m.extend_from_slice(text(LEAK_ALLOCATED));
        put_int(&mut m, ALLOCATED.load(Relaxed));
        m.push(b'\n');
    }
    let live = LIVE.load(Relaxed);
    if live != 0 {
        m.extend_from_slice(text(ERROR_PREFIX));
        m.extend_from_slice(text(LEAK_LIVE));
        put_int(&mut m, live);
        m.push(b'\n');
    }
    error(&m);
    if live == 0 { 0 } else { 102 }
}

// ---- Strings ----
// A String is a block `length + bytes` (UTF-8, no final 0), passed around by its address.
// 0 = no String: freeing it does nothing (a moved variable holds 0, src/kir.rs).

fn layout(n: usize) -> Layout {
    Layout::from_size_align(8 + n, 8).unwrap()
}

fn new_text(b: &[u8]) -> i64 {
    unsafe {
        let p = alloc(layout(b.len())) as *mut i64;
        if p.is_null() {
            handle_alloc_error(layout(b.len()));
        }
        *p = b.len() as i64;
        core::ptr::copy_nonoverlapping(b.as_ptr(), p.add(1) as *mut u8, b.len());
        made();
        p as i64
    }
}

fn bytes<'a>(s: i64) -> &'a [u8] {
    unsafe { core::slice::from_raw_parts((s as *const i64).add(1) as *const u8, *(s as *const i64) as usize) }
}

/// A String is always valid UTF-8: made from Kova texts, or checked when read from outside.
fn text_of<'a>(s: i64) -> &'a str {
    unsafe { core::str::from_utf8_unchecked(bytes(s)) }
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_str_new(b: *const u8, n: i64) -> i64 {
    new_text(unsafe { core::slice::from_raw_parts(b, n as usize) })
}

#[unsafe(no_mangle)]
pub extern "C" fn kova_str_free(s: i64) {
    if s != 0 {
        unsafe { dealloc(s as *mut u8, layout(bytes(s).len())) };
        LIVE.fetch_sub(1, Relaxed);
    }
}

