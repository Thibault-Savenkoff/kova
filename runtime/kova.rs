/// `DateTime.now`: the local time, in seconds since 1970-01-01 00:00 (src/interp.rs does the same).
#[unsafe(no_mangle)]
pub extern "C" fn kova_local_now() -> i64 {
    #[cfg(not(windows))]
    {
        let utc = (sys::now() / 1_000_000_000) as i64;
        utc + shared::local_offset(utc, sys::var("TZ").as_deref(), &|p| sys::read_file(p).ok())
    }
    #[cfg(windows)]
    sys::local_now()
}

/// `now`: the seconds since 1970 (UTC), as a Float's bits.
#[unsafe(no_mangle)]
pub extern "C" fn kova_now() -> i64 {
    let t = sys::now();
    ((t / 1_000_000_000) as f64 + (t % 1_000_000_000) as f64 / 1e9).to_bits() as i64
}

/// `sleep(seconds)`, a Float's bits: what `print` left is shown first; 0 or less waits nothing.
#[unsafe(no_mangle)]
pub extern "C" fn kova_sleep(bits: i64) -> i64 {
    let s = f64::from_bits(bits as u64);
    flush();
    if s > 0.0 && s < 1e9 {
        sys::sleep(s);
    }
    0
}

/// `random(from..to)`: the state is started at the first call.
#[unsafe(no_mangle)]
pub extern "C" fn kova_random(from: i64, to: i64) -> i64 {
    static CHANCE: Global<Option<u64>> = Global::new(None);
    let state = CHANCE.get().get_or_insert_with(|| {
        shared::seed(sys::var("KOVA_SEED").as_deref()).unwrap_or_else(|| sys::now() ^ sys::pid() << 32)
    });
    shared::random(state, from, to)
}

// ---- What the generated code and Rust's own code ask the C library for, which a Kova
// executable doesn't have ----

/// Without the decimals; `-0.5` → `-0.0`. Cranelift calls it, `floor` and `ceil` on x86-64.
/// Exact, like `floor` and `ceil` (no rounding happens), so the same as `kova run`'s.
#[cfg(not(target_os = "macos"))]
#[unsafe(no_mangle)]
pub extern "C" fn trunc(x: f64) -> f64 {
    // From 2^52 on, a Float has no decimals; NaN and infinities stay too.
    if !(x.abs() < 4503599627370496.0) {
        return x;
    }
    (x as i64 as f64).copysign(x)
}

#[cfg(not(target_os = "macos"))]
#[unsafe(no_mangle)]
pub extern "C" fn floor(x: f64) -> f64 {
    let t = trunc(x);
    if t > x { t - 1.0 } else { t }
}

#[cfg(not(target_os = "macos"))]
#[unsafe(no_mangle)]
pub extern "C" fn ceil(x: f64) -> f64 {
    let t = trunc(x);
    if t < x { t + 1.0 } else { t }
}

