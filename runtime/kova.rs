/// `s.find(part)`: the number of the character where `part` starts first, -1 if nowhere.
#[unsafe(no_mangle)]
pub extern "C" fn kova_str_find(a: i64, part: i64) -> i64 {
    let s = text_of(a);
    s.find(text_of(part)).map_or(-1, |i| s[..i].chars().count() as i64)
}

/// `s[from..to]`: characters `from` to `to` (without it), checked before by src/kir.rs.
#[unsafe(no_mangle)]
pub extern "C" fn kova_str_slice(a: i64, from: i64, to: i64) -> i64 {
    new_text(text_of(a).chars().skip(from as usize).take((to - from) as usize).collect::<String>().as_bytes())
}

/// `s.repeat(n)`: `s` `n` times; nothing for `n` <= 0.
#[unsafe(no_mangle)]
pub extern "C" fn kova_str_repeat(a: i64, n: i64) -> i64 {
    new_text(&bytes(a).repeat(n.max(0) as usize))
}

/// `words.join(", ")`: the Strings of the List with `sep` between them.
#[unsafe(no_mangle)]
pub extern "C" fn kova_str_join(l: i64, sep: i64) -> i64 {
    let words: Vec<&[u8]> = list(l).slots.iter().map(|&w| bytes(w)).collect();
    new_text(&words.join(bytes(sep)))
}

